/* Post-build: writes dist/_headers (Netlify and Cloudflare Pages format) with security headers,
   a strict Content-Security-Policy and cache rules.

   The CSP allows inline scripts by SHA-256 hash only, computed from the built HTML, so it can never
   drift from the code. Third-party origins are added only when the build needs them:
   Google Tag Manager when PUBLIC_GTM_ID is set, and the consultation endpoint's origin when
   PUBLIC_CONSULT_ENDPOINT is an absolute URL. Runs automatically after `astro build`. */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const env = process.env;

const htmlFiles = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? htmlFiles(p) : p.endsWith('.html') ? [p] : [];
});

// Inline, executable scripts (no src, not a JSON data block) → 'sha256-…' sources.
const hashes = new Set();
for (const file of htmlFiles(dist)) {
  const html = readFileSync(file, 'utf8');
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(attrs) || /application\/(ld\+)?json/.test(attrs) || !body.trim()) continue;
    hashes.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
}

const gtm = Boolean(env.PUBLIC_GTM_ID);
let endpointOrigin = '';
try { if (/^https?:\/\//.test(env.PUBLIC_CONSULT_ENDPOINT || '')) endpointOrigin = new URL(env.PUBLIC_CONSULT_ENDPOINT).origin; } catch (e) { /* relative or invalid: same origin */ }

// Google Tag Manager + GA4 hosts (https://developers.google.com/tag-platform/security/guides/csp).
const G = gtm ? {
  script: ['https://www.googletagmanager.com'],
  connect: ['https://*.google-analytics.com', 'https://*.analytics.google.com', 'https://www.googletagmanager.com'],
  img: ['https://*.google-analytics.com', 'https://www.googletagmanager.com'],
} : { script: [], connect: [], img: [] };

const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(' ')} ${G.script.join(' ')}`.trim(),
  "style-src 'self' 'unsafe-inline'",          // style="--var: …" attributes drive motion and layout
  `img-src 'self' data: ${G.img.join(' ')}`.trim(),
  "font-src 'self'",
  `connect-src 'self' ${[endpointOrigin, ...G.connect].filter(Boolean).join(' ')}`.trim(),
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# Generated by scripts/headers.mjs after each build — edit that script, not this file.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin

# Fingerprinted build output and versioned fonts never change.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable
/fonts/*
  Cache-Control: public, max-age=31536000, immutable

# Stable public assets: cache for a day, revalidate after.
/assets/*
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800
/og/*
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800
`;

writeFileSync(join(dist, '_headers'), headers);
console.log(`dist/_headers: ${hashes.size} inline script hash(es)${gtm ? ', GTM allowed' : ''}${endpointOrigin ? `, endpoint ${endpointOrigin}` : ''}`);
